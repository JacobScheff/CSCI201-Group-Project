const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function request(path, method = 'GET', body, token, expected = 200) {
  const response = await fetch(`${base}/api${path}`, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const data = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
  return data;
}
async function account(name) {
  return request('/auth/register', 'POST', { username: `${name}_${suffix}`, email: `${name}_${suffix}@example.test`, password: 'Rally-test-password-2026' });
}
async function connect(code, hello) {
  const ws = new WebSocket(`${base.replace(/^http/, 'ws')}/ws/game/${code}`);
  const client = { ws, state: null, messages: [], send: body => ws.send(JSON.stringify(body)) };
  sockets.push(client);
  ws.addEventListener('message', event => { const message = JSON.parse(event.data); client.messages.push(message); if (message.state) client.state = message.state; });
  await new Promise((resolve, reject) => { ws.addEventListener('open', resolve, { once: true }); ws.addEventListener('error', reject, { once: true }); });
  if (hello) client.send(hello);
  return client;
}
async function until(predicate, description, timeout = 6000) {
  const start = Date.now();
  while (!predicate()) { if (Date.now() - start > timeout) throw new Error(`Timed out: ${description}`); await wait(15); }
}
async function expectError(client, body, code) {
  const start = client.messages.length;
  client.send(body);
  await until(() => client.messages.slice(start).some(m => m.type === 'ERROR' && (!code || m.code === code)), `WebSocket error ${code || ''}`);
}
