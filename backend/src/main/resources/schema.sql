CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(60) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS quizzes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id BIGINT REFERENCES users(id),
  title VARCHAR(100) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  is_example BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id BIGINT NOT NULL REFERENCES quizzes(id) ON DELETE CASCADE,
  position INT NOT NULL,
  text VARCHAR(300) NOT NULL,
  type VARCHAR(10) NOT NULL CHECK (type IN ('SINGLE', 'MULTI')),
  time_limit_sec INT NOT NULL CHECK (time_limit_sec BETWEEN 5 AND 120),
  image_url VARCHAR(255),
  UNIQUE(quiz_id, position)
);
CREATE TABLE IF NOT EXISTS answer_options (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id BIGINT NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
  position INT NOT NULL CHECK (position BETWEEN 0 AND 3),
  text VARCHAR(100) NOT NULL,
  is_correct BOOLEAN NOT NULL,
  UNIQUE(question_id, position)
);
CREATE TABLE IF NOT EXISTS games (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quiz_id BIGINT REFERENCES quizzes(id) ON DELETE SET NULL,
  host_id BIGINT NOT NULL REFERENCES users(id),
  game_code CHAR(6) NOT NULL,
  status VARCHAR(12) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  ended_at TIMESTAMP WITH TIME ZONE NOT NULL,
  snapshot_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS game_players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_id BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
  user_id BIGINT REFERENCES users(id),
  display_name VARCHAR(20) NOT NULL,
  final_score INT NOT NULL,
  final_rank INT NOT NULL,
  total_response_ms BIGINT NOT NULL,
  UNIQUE(game_id, user_id)
);
CREATE TABLE IF NOT EXISTS player_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game_player_id BIGINT NOT NULL REFERENCES game_players(id) ON DELETE CASCADE,
  question_position INT NOT NULL,
  selected_option_ids TEXT NOT NULL,
  response_ms BIGINT,
  points INT NOT NULL,
  UNIQUE(game_player_id, question_position)
);
CREATE INDEX IF NOT EXISTS quizzes_owner_idx ON quizzes(owner_id);
CREATE INDEX IF NOT EXISTS history_host_idx ON games(host_id);
CREATE INDEX IF NOT EXISTS history_player_idx ON game_players(user_id);
